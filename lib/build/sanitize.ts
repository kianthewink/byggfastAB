import type {
  BuildCatalog,
  BuildCategory,
  BuildConfig,
  BuildGroup,
  BuildOption,
  ExactPrices,
  Municipality,
  PurchasePackage,
} from "./types";

/**
 * Turns untrusted input — a Server Action argument, a jsonb column, an
 * imported spreadsheet cell — into well-formed build data. Anything
 * malformed is dropped or defaulted rather than thrown, so one bad value can
 * never break a product page.
 */

type Loose = Record<string, unknown>;

function obj(value: unknown): Loose {
  return value && typeof value === "object" && !Array.isArray(value)
    ? (value as Loose)
    : {};
}

function arr(value: unknown): unknown[] {
  return Array.isArray(value) ? value : [];
}

function str(value: unknown, max = 500): string {
  return typeof value === "string" ? value.trim().slice(0, max) : "";
}

/** Non-negative whole kronor; anything else becomes 0. */
function kr(value: unknown): number {
  const n = typeof value === "number" ? value : Number(value);
  return Number.isFinite(n) && n > 0 ? Math.round(n) : 0;
}

/** Ids are generated by the admin UI; this just guards their shape. */
function id(value: unknown, fallback: string): string {
  const s = str(value, 80).replace(/[^a-zA-Z0-9_-]/g, "");
  return s || fallback;
}

/** De-duplicates ids so React keys and lookups stay unambiguous. */
function uniqueIds<T extends { id: string }>(items: T[]): T[] {
  const seen = new Set<string>();
  return items.map((item, i) => {
    let next = item.id;
    while (seen.has(next)) next = `${item.id}-${i}`;
    seen.add(next);
    return next === item.id ? item : { ...item, id: next };
  });
}

export function sanitizeExactPrices(value: unknown): ExactPrices {
  const out: ExactPrices = {};
  for (const [key, price] of Object.entries(obj(value))) {
    if (price === null || price === "" || price === undefined) continue;
    const n = Number(price);
    if (Number.isFinite(n) && n >= 0) out[id(key, key)] = Math.round(n);
  }
  return out;
}

export function sanitizeMunicipalities(value: unknown): Municipality[] {
  return uniqueIds(
    arr(value)
      .map((raw, i) => {
        const m = obj(raw);
        const factor = Number(m.priceFactor);
        return {
          id: id(m.id, `kommun-${i}`),
          name: str(m.name, 80),
          priceFactor:
            Number.isFinite(factor) && factor > 0 && factor < 10 ? factor : 1,
        };
      })
      .filter((m) => m.name)
  );
}

export function sanitizePackages(value: unknown): PurchasePackage[] {
  return uniqueIds(
    arr(value)
      .map((raw, i) => {
        const p = obj(raw);
        return {
          id: id(p.id, `paket-${i}`),
          name: str(p.name, 120),
          description: str(p.description, 1000),
          campaign: str(p.campaign, 200),
          price: kr(p.price),
          configurable: p.configurable !== false,
          exactPrices: sanitizeExactPrices(p.exactPrices),
        };
      })
      .filter((p) => p.name)
  );
}

function sanitizeOption(raw: unknown, i: number): BuildOption {
  const o = obj(raw);
  const swatch = str(o.swatch, 9);
  return {
    id: id(o.id, `val-${i}`),
    name: str(o.name, 120),
    description: str(o.description, 1000),
    price: kr(o.price),
    swatch: /^#[0-9a-fA-F]{3,8}$/.test(swatch) ? swatch : null,
    exactPrices: sanitizeExactPrices(o.exactPrices),
  };
}

function sanitizeCategory(raw: unknown, i: number): BuildCategory {
  const c = obj(raw);
  return {
    id: id(c.id, `kategori-${i}`),
    name: str(c.name, 120),
    description: str(c.description, 1000),
    multiple: c.multiple === true,
    options: uniqueIds(
      arr(c.options).map(sanitizeOption).filter((o) => o.name)
    ),
  };
}

function sanitizeGroup(raw: unknown, i: number): BuildGroup {
  const g = obj(raw);
  return {
    id: id(g.id, `flik-${i}`),
    name: str(g.name, 60),
    categories: uniqueIds(
      arr(g.categories).map(sanitizeCategory).filter((c) => c.name)
    ),
  };
}

export function sanitizeCatalog(value: unknown): BuildCatalog {
  return {
    groups: uniqueIds(
      arr(obj(value).groups).map(sanitizeGroup).filter((g) => g.name)
    ),
  };
}

/** Shape only — normalizeConfig() checks the ids against the catalog. */
export function sanitizeConfig(value: unknown): BuildConfig {
  const c = obj(value);
  const selections: Record<string, string[]> = {};
  for (const [key, ids] of Object.entries(obj(c.selections))) {
    selections[id(key, key)] = arr(ids)
      .map((v) => str(v, 80))
      .filter(Boolean)
      .slice(0, 50);
  }
  return {
    municipalityId: str(c.municipalityId, 80) || null,
    packageId: str(c.packageId, 80) || null,
    selections,
  };
}
